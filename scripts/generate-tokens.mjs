// Run after updating the committed design token snapshot.
import { readFile, writeFile } from "node:fs/promises";
const tokens = JSON.parse(
  await readFile(new URL("../src/styles/tokens.json", import.meta.url), "utf8"),
);
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const name = (path) => {
  if (path[0] === "color") return `color-${path.slice(1).join("-")}`;
  if (path[0] === "badge") return `color-${path.join("-")}`;
  if (path[0] === "font" && path[1] === "family") return `font-${path[2]}`;
  if (path[0] === "space") return `spacing-${path[1]}`;
  return path.map(kebab).join("-");
};
const ref = (v) =>
  typeof v === "string"
    ? v.replace(/\{([^}]+)\}/g, (_, p) => `var(--${name(p.split("."))})`)
    : v;
const lines = [];
function walk(value, path = []) {
  if ("$value" in value) {
    const v = value.$value;
    if (Array.isArray(v))
      lines.push(
        `  --${name(path)}: ${path[0] === "font" ? v.map((s) => (s.includes(" ") ? `"${s}"` : s)).join(", ") : `cubic-bezier(${v.join(", ")})`};`,
      );
    else if (typeof v === "object")
      for (const [k, item] of Object.entries(v))
        lines.push(`  --${name([...path, kebab(k)])}: ${ref(item)};`);
    else
      lines.push(
        `  --${name(path)}: ${path.at(-1) === "googleFontsUrl" ? `"${v}"` : ref(v)};`,
      );
    return;
  }
  for (const [k, v] of Object.entries(value))
    if (!k.startsWith("$")) walk(v, [...path, k]);
}
walk(tokens);
await writeFile(
  new URL("../src/styles/theme.css", import.meta.url),
  `/* Generated by scripts/generate-tokens.mjs from src/styles/tokens.json. */\n@theme static {\n  --color-*: initial;\n  --radius-*: initial;\n  --shadow-*: initial;\n  --breakpoint-*: initial;\n${lines.join("\n")}\n}\n`,
);
